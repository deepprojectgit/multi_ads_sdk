/// Enum representing different ad provider types
///
/// Supported providers:
/// - [admob]: Google AdMob
/// - [adx]: Google AdX
/// - [facebook]: Facebook Audience Network (Meta Ads)
enum AdProviderType {
  /// Google AdMob provider
  admob,

  /// Google AdX provider
  adx,

  /// Facebook Audience Network (Meta Ads) provider
  facebook,
}
